import { writeFileSync, mkdirSync, existsSync, unlinkSync, chmodSync, lstatSync, rmSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";
import {
  buildInstalledCliWrapper,
  COMPANION_BIN_DIR,
  LOCAL_BIN_DIR,
  resolveStableWrapperScriptPath,
} from "./cli-wrapper-paths.js";

const CLAUDE_SKILL_DIR = join(homedir(), ".claude", "skills", "quest");
const AGENTS_SKILL_DIR = join(homedir(), ".agents", "skills", "quest");
const CLAUDE_MEMORY_SKILL_DIR = join(homedir(), ".claude", "skills", "memory");
const AGENTS_MEMORY_SKILL_DIR = join(homedir(), ".agents", "skills", "memory");
const OLD_SLASH_COMMAND = join(homedir(), ".claude", "commands", "quest.md");
const OLD_API_DOC = join(homedir(), ".companion", "questmaster", "API.md");
const TEMPLATE_PATH = join(dirname(fileURLToPath(import.meta.url)), "templates", "quest-skill-docs.md");
const MEMORY_COMPLETION_TEMPLATE_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  "templates",
  "quest-memory-completion.md",
);
const MEMORY_SKILL_TEMPLATE_PATH = join(dirname(fileURLToPath(import.meta.url)), "templates", "memory-skill-docs.md");
const GENERATED_QUEST_SKILL_FILES = [
  { relativePath: "SKILL.md", templatePath: TEMPLATE_PATH },
  { relativePath: "memory-completion.md", templatePath: MEMORY_COMPLETION_TEMPLATE_PATH },
] as const;
const GENERATED_MEMORY_SKILL_FILES = [{ relativePath: "SKILL.md", templatePath: MEMORY_SKILL_TEMPLATE_PATH }] as const;

type GeneratedQuestSkillFile = {
  relativePath: string;
  content: string;
};

let questSkillFiles: GeneratedQuestSkillFile[] | null = null;
let memorySkillFiles: GeneratedQuestSkillFile[] | null = null;

async function getQuestSkillFiles(): Promise<GeneratedQuestSkillFile[]> {
  questSkillFiles ??= await readSkillTemplates(GENERATED_QUEST_SKILL_FILES);
  return questSkillFiles;
}

async function getMemorySkillFiles(): Promise<GeneratedQuestSkillFile[]> {
  memorySkillFiles ??= await readSkillTemplates(GENERATED_MEMORY_SKILL_FILES);
  return memorySkillFiles;
}

function readSkillTemplates(
  files: readonly { relativePath: string; templatePath: string }[],
): Promise<GeneratedQuestSkillFile[]> {
  return Promise.all(
    files.map(async (file) => ({
      relativePath: file.relativePath,
      content: await readFile(file.templatePath, "utf-8"),
    })),
  );
}

/**
 * Set up Questmaster CLI integration on server startup:
 * 1. Write copied global wrapper scripts at ~/.companion/bin/quest, memory, and stream,
 *    with ~/.local/bin shims for them and for takode
 * 2. Write the quest and memory agent skills for Claude and the shared non-Claude skill home
 * 3. Clean up old files (slash command, API.md)
 */
export async function ensureQuestmasterIntegration(port: number, packageRoot: string): Promise<void> {
  void port;
  await writeWrapperScripts(packageRoot);
  writeLocalPathShim();
  writeRipgrepShim();
  const skillFiles = await getQuestSkillFiles();
  writeAgentSkill(CLAUDE_SKILL_DIR, skillFiles);
  writeAgentSkill(AGENTS_SKILL_DIR, skillFiles);
  const memoryFiles = await getMemorySkillFiles();
  writeAgentSkill(CLAUDE_MEMORY_SKILL_DIR, memoryFiles);
  writeAgentSkill(AGENTS_MEMORY_SKILL_DIR, memoryFiles);
  cleanupOldFiles();
  console.log("[quest-integration] CLI wrappers and quest/memory agent skills installed");
}

async function writeWrapperScripts(packageRoot: string): Promise<void> {
  mkdirSync(COMPANION_BIN_DIR, { recursive: true }); // sync-ok: quest setup, not called during message handling
  for (const commandName of ["quest", "memory", "stream"]) {
    const sharedWrapperPath = join(COMPANION_BIN_DIR, commandName);
    const stableScript = await resolveStableWrapperScriptPath(packageRoot, commandName);
    const sharedWrapper = buildInstalledCliWrapper(commandName, stableScript);
    writeFileSync(sharedWrapperPath, sharedWrapper, "utf-8"); // sync-ok: quest setup, not called during message handling
    chmodSync(sharedWrapperPath, 0o755); // sync-ok: quest setup, not called during message handling
  }
}

/**
 * Login shells that reset PATH (Codex runs commands through one) drop
 * ~/.companion/bin, so ~/.local/bin gets shims for the agent CLIs too.
 * `takode`'s own wrapper is written by the Takode integration.
 */
function writeLocalPathShim(): void {
  mkdirSync(LOCAL_BIN_DIR, { recursive: true });
  for (const commandName of ["quest", "memory", "stream", "takode"]) {
    const shimPath = join(LOCAL_BIN_DIR, commandName);
    const shim = `#!/bin/bash
# Auto-generated by Companion server. Do not edit.
exec "$HOME/.companion/bin/${commandName}" "$@"
`;

    writeFileSync(shimPath, shim, "utf-8"); // sync-ok: quest setup, not called during message handling
    chmodSync(shimPath, 0o755); // sync-ok: quest setup, not called during message handling
  }
}

function writeRipgrepShim(): void {
  mkdirSync(LOCAL_BIN_DIR, { recursive: true });
  const shimPath = join(LOCAL_BIN_DIR, "rg");
  const shim = `#!/bin/bash
# Auto-generated by Companion server. Do not edit.

# Prefer a real ripgrep binary when present.
for candidate in /usr/bin/rg /usr/local/bin/rg "$HOME/.cargo/bin/rg" "$HOME/.nix-profile/bin/rg"; do
  if [ -x "$candidate" ]; then
    exec "$candidate" "$@"
  fi
done

if [ "$1" = "--version" ] || [ "$1" = "-V" ]; then
  echo "rg (companion shim) 0.0.0"
  echo "fallback: grep/find compatibility mode"
  exit 0
fi

if [ "$1" = "--files" ]; then
  shift
  root="."
  while [ "$#" -gt 0 ]; do
    case "$1" in
      --glob|-g) shift 2 ;;
      -*) shift ;;
      *) root="$1"; shift ;;
    esac
  done
  find "$root" -type f -not -path '*/.git/*' -not -path '*/node_modules/*' | sed 's#^\\./##'
  exit 0
fi

if [ "$1" = "--help" ] || [ "$1" = "-h" ]; then
  echo "rg (companion shim): partial compatibility mode using grep/find"
  echo "supports: --version, --files, and common search flags"
  exit 0
fi

if [ "$#" -lt 1 ]; then
  echo "rg shim: usage: rg [OPTIONS] PATTERN [PATH ...] or rg --files [PATH]" >&2
  exit 2
fi

grep_args=(
  -R
  -I
  -n
  -E
  --binary-files=without-match
  --exclude-dir=.git
)
positional=()

while [ "$#" -gt 0 ]; do
  case "$1" in
    --)
      shift
      while [ "$#" -gt 0 ]; do
        positional+=("$1")
        shift
      done
      break
      ;;
    --hidden|-uu|-uuu)
      # Ignored: grep -R already walks hidden paths by default.
      shift
      ;;
    --glob|-g)
      if [ "$#" -lt 2 ]; then
        echo "rg shim: $1 requires a pattern argument" >&2
        exit 2
      fi
      grep_args+=(--include "$2")
      shift 2
      ;;
    -g*)
      grep_args+=(--include "$\{1#-g}")
      shift
      ;;
    -n|-S)
      # -n is already enabled, -S (smart case) is not supported.
      shift
      ;;
    -F|-i|-w|-x|-v|-l|-L|-c|-o|-s|-h|-H)
      grep_args+=("$1")
      shift
      ;;
    -e|-f)
      if [ "$#" -lt 2 ]; then
        echo "rg shim: $1 requires an argument" >&2
        exit 2
      fi
      grep_args+=("$1" "$2")
      shift 2
      ;;
    -*)
      grep_args+=("$1")
      shift
      ;;
    *)
      positional+=("$1")
      shift
      ;;
  esac
done

if [ "$\{#positional[@]}" -lt 1 ]; then
  echo "rg shim: missing PATTERN" >&2
  exit 2
fi

pattern="$\{positional[0]}"
if [ "$\{#positional[@]}" -eq 1 ]; then
  positional+=(.)
fi

exec grep "$\{grep_args[@]}" -- "$pattern" "$\{positional[@]:1}"
`;

  writeFileSync(shimPath, shim, "utf-8"); // sync-ok: quest setup, not called during message handling
  chmodSync(shimPath, 0o755); // sync-ok: quest setup, not called during message handling
}

function writeAgentSkill(skillDir: string, files: GeneratedQuestSkillFile[]): void {
  prepareGeneratedSkillDir(skillDir);
  for (const file of files) {
    const skillPath = join(skillDir, file.relativePath);
    mkdirSync(dirname(skillPath), { recursive: true }); // sync-ok: quest setup, not called during message handling
    writeFileSync(skillPath, file.content, "utf-8"); // sync-ok: quest setup, not called during message handling
  }
}

function prepareGeneratedSkillDir(skillDir: string): void {
  try {
    const stat = lstatSync(skillDir); // sync-ok: quest setup, not called during message handling
    if (stat.isSymbolicLink()) {
      unlinkSync(skillDir); // sync-ok: quest setup, not called during message handling
    } else if (!stat.isDirectory()) {
      rmSync(skillDir, { recursive: true, force: true }); // sync-ok: quest setup, not called during message handling
    }
  } catch (error) {
    if (!isMissingPathError(error)) throw error;
  }
  mkdirSync(skillDir, { recursive: true });
}

function isMissingPathError(error: unknown): boolean {
  return typeof error === "object" && error !== null && (error as { code?: string }).code === "ENOENT";
}

function cleanupOldFiles(): void {
  // Remove old slash command (superseded by agent skill)
  if (existsSync(OLD_SLASH_COMMAND)) {
    // sync-ok: quest setup, not called during message handling
    try {
      unlinkSync(OLD_SLASH_COMMAND); // sync-ok: quest setup, not called during message handling
    } catch {
      // Ignore
    }
  }
  // Remove old API.md (superseded by CLI)
  if (existsSync(OLD_API_DOC)) {
    // sync-ok: quest setup, not called during message handling
    try {
      unlinkSync(OLD_API_DOC); // sync-ok: quest setup, not called during message handling
    } catch {
      // Ignore
    }
  }
}
